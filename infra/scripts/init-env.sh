#!/bin/sh
# Create infra/compose/.env with fresh random secrets for the self-host bundle.
# Safe to re-run: an existing file is never overwritten, because changing the
# database passwords or VAULT_KEY after first start would lock you out.
#
#   sh infra/scripts/init-env.sh
#
# Needs only a POSIX shell, od and base64 (Linux, macOS, WSL, Git Bash).
set -eu

dir=$(CDPATH= cd -- "$(dirname -- "$0")/../compose" && pwd)
file="$dir/.env"

if [ -e "$file" ]; then
  echo "$file already exists; leaving it unchanged."
  exit 0
fi

# n random bytes as lowercase hex (URL-safe, so fine inside connection strings)
hex() { od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'; }
# 32 random bytes as base64 (the format VAULT_KEY requires)
b64_32() { head -c 32 /dev/urandom | base64 | tr -d '\n'; }

umask 077
cat > "$file" <<EOF
# Generated by infra/scripts/init-env.sh. Keep this file private and back it up:
# without VAULT_KEY, stored credentials cannot be decrypted.

# Address you open in the browser. Change both together if you use another port.
APP_PORT=3000
APP_URL=http://localhost:3000
# Extra host names to accept, comma-separated (e.g. your Tailscale machine name)
ALLOWED_HOSTS=

POSTGRES_PASSWORD=$(hex 24)
APP_DB_PASSWORD=$(hex 24)

AUTH_SECRET=$(hex 32)
VAULT_KEY=$(b64_32)

INNGEST_EVENT_KEY=$(hex 16)
INNGEST_SIGNING_KEY=$(hex 32)

SEARXNG_SECRET=$(hex 32)

# The app and the agents' computer share this; agents never see it.
SANDBOX_TOKEN=$(hex 32)
# Sites the agents' computer may reach, comma-separated (each covers its
# subdomains), or * for any public site. Private addresses are always refused.
# With a list, add pypi.org,files.pythonhosted.org so agents can pip install.
SANDBOX_EGRESS_ALLOW=*

LOG_LEVEL=info
EOF

echo "Wrote $file"
echo "Next: docker compose -f infra/compose/docker-compose.selfhost.yml up -d --build"
